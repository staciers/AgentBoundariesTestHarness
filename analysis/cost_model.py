"""Q6: what the runtime costs, as a latency cost model (exploratory, post hoc).

    .venv/bin/python analysis/cost_model.py [bench.json] [llm_run_dir] [out_dir]
    (defaults: docs/cost/bench.json, runs/real-ledger-20261028-111807, docs/cost)

Three parts:
1. **What the runtime does,** from ``analysis/overhead_bench.py``: the same scripted agent with and
   without the runtime on the real ledger, so differences are the runtime's own work (extra
   HTTP requests, deliberate waits, payment-call latency).
2. **The cost model:** runtime overhead per faulted payment = extra requests × RTT + waits ×
   2.5 s, evaluated at round-trip times from localhost to intercontinental. A request's server
   time on this stack is a few milliseconds and is counted inside the measured local RTT.
3. **What it costs with LLM agents,** from the real-services run: model calls, tool calls,
   tokens, model cost and wall time per episode, with and without the runtime, on both
   substrates.
"""
from __future__ import annotations

import json
import os
import statistics
import sys
from collections import defaultdict

sys.path.insert(0, ".")
from abh.metrics import load_episodes  # noqa: E402

HW = "timeout_after_execution+delayed_visibility"
PC = "partial_mutation+timeout_after_execution"
ARMS = [("no fault", "none", "P1", None), ("hidden write", HW, "P1[expose_keys=False]", "P6[threshold=0.7]"),
        ("partial commit", PC, "P1", "P6[threshold=0.7]")]
RTTS = [("localhost (measured)", None), ("same zone", 1), ("same region", 5), ("cross-region", 70),
        ("intercontinental", 150)]


def med(xs):
    return statistics.median(xs) if xs else float("nan")


def main(bench_path: str = "docs/cost/bench.json", run_dir: str = "runs/real-ledger-20261028-111807",
         out_dir: str = "docs/cost") -> None:
    bench = json.load(open(bench_path))
    local = bench["local_request_ms"]["median"]
    wait_s = bench["wait_ms"] / 1000
    s = {(r["condition"], r["policy"]): r for r in bench["summary"]}
    out = ["# Q6: what the runtime costs (exploratory)", "",
           "Generated by `analysis/cost_model.py`. **Not pre-registered.** Sources: "
           f"[`bench.json`](bench.json) (`analysis/overhead_bench.py`, {bench['seeds']} episodes per cell, scripted "
           f"agent, real ledger) and `{run_dir}` (LLM agents, real and simulated ledger).", "",
           "## 1. What the runtime does (same agent, with and without it)", "",
           "The scripted `naive` agent has no checks or recovery of its own, so the differences between the rows "
           "of each condition are the runtime's own work. Medians per episode.", "",
           "| Condition | Runtime | Outcome | Agent requests | Runtime requests | Waits (× 2.5 s) | "
           "Payment call | Episode |", "|---|---|---|---|---|---|---|---|"]
    for cond in ("none", "hidden write", "partial commit"):
        for pol in ("no runtime", "runtime (P6)", "runtime (P6) + fast path"):
            r = s[(cond, pol)]
            outcome = f"harm {r['harm']}/{r['episodes']}" if r["harm"] else f"safe {r['episodes']}/{r['episodes']}"
            out.append(f"| {cond if pol == 'no runtime' else ''} | {pol} | {outcome} | {r['agent_requests']:g} | "
                       f"{r['runtime_requests']:g} | {r['waits']:g} | {r['first_payment_call_ms'] / 1000:.2f} s | "
                       f"{r['episode_ms'] / 1000:.2f} s |")
    out += ["", f"A plain request through the proxy and service to the fast replica took {local:g} ms (median; p90 "
            f"{bench['local_request_ms']['p90']:g} ms) on this machine. The 3 s client timeout is part of both rows "
            "under a fault.", "",
            "## 2. Cost model", "",
            "Runtime overhead per payment call = extra requests × RTT + waits × 2.5 s. Requests here are sequential, "
            "so RTTs add. Overhead in seconds:", "",
            "| Condition | Extra requests | Waits | " + " | ".join(
                f"{n} ({local:g} ms)" if v is None else f"{n} ({v} ms)" for n, v in RTTS) + " |",
            "|---|---|---|" + "---|" * len(RTTS)]
    for cond in ("none", "hidden write", "partial commit"):
        for pol in ("runtime (P6)", "runtime (P6) + fast path"):
            r, base = s[(cond, pol)], s[(cond, "no runtime")]
            extra = r["runtime_requests"] + max(0, r["agent_requests"] - base["agent_requests"])
            waits = r["waits"]
            cells = []
            for _, v in RTTS:
                rtt = (local if v is None else v) / 1000
                cells.append(f"{extra * rtt + waits * wait_s:.2f}")
            label = cond if pol == "runtime (P6)" else "↳ with fast path"
            out.append(f"| {label} | {extra:g} | {waits:g} | " + " | ".join(cells) + " |")
    out += ["", "- **No fault (the common case):** one extra read to verify the payment landed, so the overhead is one "
            f"RTT, from {local:.0f} ms locally to 150 ms intercontinental. No waits.",
            "- **Under a fault, the waits dominate.** Even at 150 ms RTT the requests add about 1–2 s; the polling "
            "adds 7.5–10 s. Waits are a runtime parameter (4 polls, 2.5 s apart), sized to the replication lag they "
            "must outlast, so their cost tracks the deployment's lag, not its RTT.",
            "- **Partial commit was the most expensive case, and the fast path removes almost all of it.** "
            "Without it, the runtime polls for a completed payment that a partial commit can never produce, then "
            "compensates. With it (`inspect_partial`: the contract offers a consistent lookup of a keyed attempt, "
            "which waits for any attempt in flight), the runtime learns at once that the attempt is partial, "
            "compensates and retries: no waits, and the payment call returns about 0.2 s after the client's "
            "timeout instead of about 10 s.",
            "- **The fast path doesn't help a hidden write,** and costs it one extra request. The write is "
            "complete, so the runtime still waits until it is visible before reporting success, so that the "
            "agent never reads state older than its own result. Visibility lag sets that cost."]

    eps = [e for e in load_episodes(os.path.join(run_dir, "episodes.jsonl")) if "error" not in e]
    groups = defaultdict(list)
    for e in eps:
        groups[(e["domain"], e["faults"], e["policy"])].append(e)
    out += ["", "## 3. With LLM agents (real-services run)", "",
            "Measured before the fast path existed (P6 without it). "
            "Means per episode over 6 models × 30 seeds, except wall time (median; real stack only, since the "
            "simulator's clock is simulated). P1 is the agent recovering on its own. The fault arms compare "
            "P1 without keys (hidden write) or with keys (partial commit) against P6.", "",
            "| Condition | Substrate | Policy | Harm | Model calls | Agent tool calls | Tokens (in + out) | Model cost | "
            "Wall time |", "|---|---|---|---|---|---|---|---|---|"]
    for name, faults, p1, p6 in ARMS:
        for dom in ("ledger_real", "ledger"):
            for pol in (p1, p6):
                if pol is None:
                    continue
                es = groups[(dom, faults, pol)]
                if not es:
                    continue
                mean = lambda f: sum(map(f, es)) / len(es)
                wall = f"{med([e['sim_duration_ms'] for e in es]) / 1000:.1f} s" if dom == "ledger_real" else "—"
                out.append(f"| {name} | {'real' if dom == 'ledger_real' else 'simulated'} | {pol} | "
                           f"{sum(e['harm'] for e in es)}/{len(es)} | {mean(lambda e: e['model_calls']):.2f} | "
                           f"{mean(lambda e: e['agent_tool_calls']):.2f} | "
                           f"{mean(lambda e: e['input_tokens'] + e['output_tokens']):,.0f} | "
                           f"${mean(lambda e: e['model_cost_usd']):.4f} | {wall} |")
    turn = med([e["model_latency_ms"] / e["model_calls"] for e in eps if e["model_calls"] and e["domain"] == "ledger_real"])
    p = lambda dom, f, pol, k: sum(e[k] for e in groups[(dom, f, pol)]) / max(1, len(groups[(dom, f, pol)]))
    calls = [(p("ledger_real", f, a, "model_calls"), p("ledger_real", f, b, "model_calls")) for _, f, a, b in ARMS[1:]]
    wall = lambda f, pol: med([e["sim_duration_ms"] for e in groups[("ledger_real", f, pol)]]) / 1000
    tok = lambda f, pol: p("ledger_real", f, pol, "input_tokens") + p("ledger_real", f, pol, "output_tokens")
    (_, hw, hw1, hw6), (_, pc, pc1, pc6) = ARMS[1:]
    out += ["", "- **Under a fault, the runtime replaces the agent's recovery turns.** On the real stack, with no "
            f"harm: hidden write, model calls {calls[0][0]:.1f} → {calls[0][1]:.1f} and tokens "
            f"{1 - tok(hw, hw6) / tok(hw, hw1):.0%} fewer, at similar wall time ({wall(hw, hw1):.1f} → "
            f"{wall(hw, hw6):.1f} s); partial commit, model calls {calls[1][0]:.1f} → {calls[1][1]:.1f} and tokens "
            f"{1 - tok(pc, pc6) / tok(pc, pc1):.0%} fewer, but {wall(pc, pc6) - wall(pc, pc1):.1f} s slower "
            f"({wall(pc, pc1):.1f} → {wall(pc, pc6):.1f} s): the avoidable polling in part 2. The agent never sees "
            "the fault.",
            f"- **For scale,** the median model turn on the real stack took {turn / 1000:.1f} s. The runtime's "
            f"no-fault overhead, one RTT, is about {turn / bench['local_request_ms']['median']:.0f}× smaller locally "
            f"and about {turn / 150:.0f}× smaller at an intercontinental 150 ms. Its fault-path waits (7.5–10 s) "
            f"equal about {7.5 / (turn / 1000):.0f}–{10 / (turn / 1000):.0f} model turns.",
            "- **The simulator's cost figures match the real stack's** (model calls, tool calls, tokens), so the "
            "cost results from the simulated studies (Stage A's 20% fewer model calls) carry over."]
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "cost_model.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:])
