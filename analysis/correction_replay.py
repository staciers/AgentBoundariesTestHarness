"""Replay every committed run under the current code and report what changed (writes nothing to runs/).

    .venv/bin/python analysis/correction_replay.py [out_dir]     (default docs/corrections)

Used for the November 2026 runtime correction (docs/corrections/2026-11-runtime-verification.md):
each episode with a saved trace is replayed with its recorded agent decisions (no model calls)
and compared with the original record on outcome, success, harm, the faithfulness fields, the
injected faults, and every runtime outcome and agent-visible result. Episodes on real services
(domain ledger_real) need the live stack and are counted separately.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from concurrent.futures import ProcessPoolExecutor

sys.path.insert(0, ".")
from abh.rescore import check_run  # noqa: E402


def committed_runs() -> list:
    files = subprocess.run(["git", "ls-files", "runs"], capture_output=True, text=True, check=True).stdout.split()
    return sorted({f.split("/")[1] for f in files if f.endswith("spec.json")})


def main(out_dir: str = "docs/corrections") -> None:
    os.makedirs(out_dir, exist_ok=True)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = bool(subprocess.run(["git", "status", "--porcelain", "abh"], capture_output=True, text=True).stdout)
    runs = committed_runs()
    t0 = time.time()
    with ProcessPoolExecutor() as ex:
        results = list(ex.map(check_run, [os.path.join("runs", r) for r in runs]))
    keys = ("episodes", "identical", "changed", "skipped_real_services", "errored", "no_trace", "no_config")
    total = {k: sum(r["stats"][k] for r in results) for k in keys}
    report = {"generated": time.strftime("%Y-%m-%dT%H:%M:%S"), "code": commit + (" + uncommitted abh/ changes" if dirty else ""),
              "seconds": round(time.time() - t0, 1), "total": total, "runs": results}
    with open(os.path.join(out_dir, "replay-2026-11.json"), "w") as f:
        json.dump(report, f, indent=2)

    md = ["# Replay of all committed runs under the corrected runtime", "",
          f"Generated by `analysis/correction_replay.py` on {report['generated']} from code `{report['code']}`. "
          "Each episode was replayed from its saved trace (recorded agent decisions, no model calls) and "
          "compared with the original record on outcome, success, harm, the replay-faithfulness fields, the "
          "injected faults, each runtime outcome (state and actions), and each result's kind and error flag. "
          "Traces don't record response content; it was compared separately, between the code before and "
          "after the fix (`responses-2026-11.json`). Nothing in `runs/` was modified.",
          "", f"**Replayed {total['identical'] + total['changed']:,} episodes: {total['identical']:,} identical, "
          f"{total['changed']} changed.** {total['skipped_real_services']} real-services episodes need the live "
          f"stack and were not replayed; {total['errored']} episodes had errored in the original run "
          f"(excluded there too); {total['no_trace']} have no saved trace.", "",
          "How to read this, including why some pilot episodes differ under the code before the fix as well, "
          "is in [the correction note](2026-11-runtime-verification.md).", "",
          "| Run | Episodes | Identical | Changed | Real services (not replayed) | Errored | No trace |",
          "|---|---|---|---|---|---|---|"]
    for r in results:
        s = r["stats"]
        md.append(f"| `{r['run']}` | {s['episodes']} | {s['identical']} | {s['changed']} | "
                  f"{s['skipped_real_services']} | {s['errored']} | {s['no_trace']} |")
    md.append(f"| **all** | **{total['episodes']}** | **{total['identical']}** | **{total['changed']}** | "
              f"**{total['skipped_real_services']}** | **{total['errored']}** | **{total['no_trace']}** |")
    changed = [(r["run"], c) for r in results for c in r["changed"]]
    if changed:
        md += ["", "## Changed episodes", "", "| Run | Episode | Fields | Before | After |", "|---|---|---|---|---|"]
        for run, c in changed:
            md.append(f"| `{run}` | `{c['key']}` | {', '.join(c['fields'])} | {c['before']} | {c['after']} |")
    with open(os.path.join(out_dir, "replay-2026-11.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md[:6]))
    print(json.dumps(total))


if __name__ == "__main__":
    main(*sys.argv[1:])
